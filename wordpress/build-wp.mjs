// Builds the WordPress theme and plugin packages from the Solid One source.
//   node wordpress/build-wp.mjs   ->  wordpress/dist/solid.zip, solid-core.zip, seed.json
// The theme CSS is the static site's CSS (base + Solid One) plus Elementor compatibility rules,
// so the WordPress build stays pixel-identical when the design changes.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import * as D from '../src/data.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.join(here, '..');
const read = (p) => fs.readFileSync(path.join(repo, p), 'utf8');
const theme = path.join(here, 'solid');
const plugin = path.join(here, 'solid-core');
const dist = path.join(here, 'dist');
fs.mkdirSync(path.join(theme, 'assets/brand'), { recursive: true });
fs.mkdirSync(dist, { recursive: true });

/* ── CSS ── */
const css = read('src/base.css') + '\n' + read('src/themes/one.css');

// Elementor's frontend sets `.elementor img{height:auto;max-width:100%}`, which beats the design's
// single-class image rules. Repeat every image rule scoped to .elementor so the design wins again.
function imgRules(text) {
  const out = [];
  let i = 0;
  const walk = (src, wrap) => {
    let j = 0;
    while (j < src.length) {
      const open = src.indexOf('{', j);
      if (open < 0) break;
      const sel = src.slice(j, open).trim();
      // find matching close
      let depth = 1, k = open + 1;
      while (k < src.length && depth) { if (src[k] === '{') depth++; else if (src[k] === '}') depth--; k++; }
      const body = src.slice(open + 1, k - 1);
      if (sel.startsWith('@media')) walk(body, sel);
      else if (!sel.startsWith('@') && /\bimg\b/.test(sel) && /(height|max-width|width)\s*:/.test(body)) {
        const scoped = sel.split(',').filter((s) => /\bimg\b/.test(s)).map((s) => '.elementor ' + s.trim()).join(',');
        const rule = `${scoped}{${body}}`;
        out.push(wrap ? `${wrap}{${rule}}` : rule);
      }
      j = k;
    }
  };
  walk(text.replace(/\/\*[\s\S]*?\*\//g, ''));
  return out.join('\n');
}

// Elementor registers --gap as a non-inherited property, which blanks the design's --gap inside Elementor pages.
const designGap = (css.match(/--gap:([^;}]+)/) || [])[1] || '36px';
const compat = `
/* ───────── WordPress and Elementor compatibility ───────── */
body[class*="elementor-kit-"]{--widgets-spacing:0px 0px;--widgets-spacing-row:0px;--widgets-spacing-column:0px}
:root{--container-default-padding-top:0px;--container-default-padding-right:0px;--container-default-padding-bottom:0px;--container-default-padding-left:0px}
.elementor .e-con.solid-flow{--padding-top:0px;--padding-right:0px;--padding-bottom:0px;--padding-left:0px;--row-gap:0px;--column-gap:0px;--display:block;padding:0;display:block}
.elementor .e-con.solid-flow *{--gap:${designGap}}
.elementor .e-con.solid-flow>.elementor-widget{width:100%;max-width:none;margin:0}
.elementor-editor-active [data-reveal],.elementor-editor-preview [data-reveal]{opacity:1;transform:none}
.elementor-widget-container>.wrap,.elementor-widget-container>section{margin-block:0}
/* WordPress serves photos in their original shape (the static site used pre-cropped ones):
   stop a tall photo from stretching its aspect-ratio box. */
.card__media,.conv__media,.person__media,.phead__av,.byline__av{min-height:0}
.card__media img,.conv__media img,.person__media img{position:absolute;inset:0}
.person__media{position:relative}
.admin-bar .menu,.admin-bar .search{top:var(--wp-admin--admin-bar--height,0px)}
.screen-reader-text{position:absolute!important;width:1px;height:1px;overflow:hidden;clip:rect(1px,1px,1px,1px)}
.prose .alignleft{float:left;margin:6px 24px 12px 0}.prose .alignright{float:right;margin:6px 0 12px 24px}.prose .aligncenter{margin-inline:auto}
.prose img{height:auto;border-radius:var(--radius)}
.nav-links{display:flex;gap:12px;justify-content:center;margin-top:40px;font-size:14px}.nav-links .current{color:var(--red)}
${imgRules(css)}
`;
fs.writeFileSync(path.join(theme, 'assets/solid.css'), `/* SOLID — Solid One design. Generated by wordpress/build-wp.mjs from src/base.css and src/themes/one.css. Edit those, then rebuild. */\n${css}\n${compat}`);

/* ── JS: same behaviour as the static site; search reads the WordPress index ── */
let js = read('src/app.js');
const swaps = [
  ["fetch(root + 'assets/index.json')", "fetch(html.getAttribute('data-search-index'))"],
  ["root + 'story/' + s.u + '/\"", "s.u + '\""],
];
for (const [a, b] of swaps) {
  if (!js.includes(a)) throw new Error('app.js changed; update build-wp.mjs swap: ' + a);
  js = js.replace(a, () => b);
}
js = js.replace("// Forms (prototype: no submission)", () => `// Copy link
  $$('[data-copy-link]').forEach(function (a) {
    a.addEventListener('click', function (e) {
      if (!navigator.clipboard) return;
      e.preventDefault();
      navigator.clipboard.writeText(a.href).then(function () { a.setAttribute('aria-label', 'Link copied'); a.classList.add('is-copied'); });
    });
  });

  // Forms (prototype: no submission)`);
fs.writeFileSync(path.join(theme, 'assets/app.js'), js);

/* ── Logo and brand files ── */
fs.copyFileSync(path.join(repo, 'src/logo.json'), path.join(theme, 'assets/logo.json'));
for (const [from, to] of [['favicon/favicon.ico', 'favicon.ico'], ['favicon/apple-touch-icon.png', 'apple-touch-icon.png'], ['favicon/favicon-512.png', 'icon-512.png'], ['sm-mark-red.svg', 'sm-mark-red.svg']])
  fs.copyFileSync(path.join(repo, 'brand', from), path.join(theme, 'assets/brand', to));

/* ── Seed content for the importer ── */
const seed = {
  photos: D.P,
  sections: D.SECTIONS.map((s, i) => ({ ...s, order: i + 1 })),
  authors: D.AUTHORS,
  stories: D.STORIES.map((s) => ({ title: s.title, slug: s.slug, dek: s.dek, section: s.section, sub: s.sub, img: s.img, author: s.author.slug, mins: s.mins, date: s.iso, i: s.i })),
  conversations: D.CONVERSATIONS,
  honourees: D.HONOUREES,
  categories100: D.CATEGORIES_100,
  legal: D.LEGAL,
};
fs.writeFileSync(path.join(dist, 'seed.json'), JSON.stringify(seed));

/* ── Zip packages (bsdtar writes forward-slash paths, which Linux servers need) ── */
const zip = (dir, name) => {
  const out = path.join(dist, name);
  fs.rmSync(out, { force: true });
  const tar = process.platform === 'win32' ? path.join(process.env.SystemRoot || 'C:\\Windows', 'System32', 'tar.exe') : 'zip';
  if (process.platform === 'win32') execFileSync(tar, ['-a', '-c', '-f', name, '-C', path.dirname(dir), path.basename(dir)], { cwd: dist });
  else execFileSync('zip', ['-rq', out, path.basename(dir)], { cwd: path.dirname(dir) });
  return out;
};
zip(theme, 'solid.zip');
zip(plugin, 'solid-core.zip');
console.log('Built theme and plugin into', dist);
